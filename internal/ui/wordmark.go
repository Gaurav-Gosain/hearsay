// unknownGlyph stands in for a rune the font does not have.
var unknownGlyph = []string{"...", "###", "#.#", "#.#", "#.#", "###"}

// wordGlyphs returns the bitmaps of a name, lower-cased.
func wordGlyphs(word string) [][]string {
	var out [][]string
	for _, r := range strings.TrimSpace(word) {
		g, ok := wordFont[unicode.ToLower(r)]
		if !ok {
			g = unknownGlyph
		}
		out = append(out, g)
	}
	return out
}

// wordmarkWidth is the width of the drawn wordmark in cells.
func wordmarkWidth(word string) int {
	w := 0
	for i, g := range wordGlyphs(word) {
		if i > 0 {
			w++
		}
		w += len(g[0])
	}
	return w
}

// wordmarkOK reports whether the font has every rune of the name.
func wordmarkOK(word string) bool {
	if strings.TrimSpace(word) == "" {
		return false
	}
	for _, r := range word {
		if _, ok := wordFont[unicode.ToLower(r)]; !ok {
			return false
		}
	}
	return true
}
